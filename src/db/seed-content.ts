// Compact content DSL for seeding. All texts are Persian.
export type SeedQuestion =
  | { t: "mc"; q: string; o: string[]; a: number; e?: string; d?: number }
  | { t: "tf"; q: string; a: boolean; e?: string; d?: number }
  | { t: "fb"; q: string; a: string[]; e?: string; d?: number }
  | { t: "dd"; q: string; pairs: [string, string][]; e?: string; d?: number }
  | { t: "fc"; q: string; back: string; d?: number }
  | { t: "sc"; q: string; scenario: string; o: string[]; a: number; e?: string; d?: number }
  | { t: "img"; q: string; img: string; o: string[]; a: number; e?: string; d?: number };

export type SeedStation = { title: string; icon?: string; desc?: string; questions: SeedQuestion[] };
export type SeedTopic = { title: string; desc?: string; stations: SeedStation[] };
export type SeedCategory = {
  slug: string;
  title: string;
  description: string;
  color: string;
  icon: string;
  topics: SeedTopic[];
};

const mc = (q: string, o: string[], a: number, e = "", d = 1): SeedQuestion => ({ t: "mc", q, o, a, e, d });
const tf = (q: string, a: boolean, e = "", d = 1): SeedQuestion => ({ t: "tf", q, a, e, d });
const fb = (q: string, a: string[], e = "", d = 2): SeedQuestion => ({ t: "fb", q, a, e, d });
const dd = (q: string, pairs: [string, string][], e = "", d = 2): SeedQuestion => ({ t: "dd", q, pairs, e, d });
const fc = (q: string, back: string, d = 1): SeedQuestion => ({ t: "fc", q, back, d });
const sc = (scenario: string, q: string, o: string[], a: number, e = "", d = 3): SeedQuestion => ({ t: "sc", q, scenario, o, a, e, d });
const img = (q: string, image: string, o: string[], a: number, e = "", d = 2): SeedQuestion => ({ t: "img", q, img: image, o, a, e, d });

